function basate_nab_seed_seo_tags() {
    // 1. Seed Product SEO Tags (product_tag)
    $prod_map = basate_nab_get_product_seo_tags_map();
    foreach ($prod_map as $prod_id => $data) {
        $product = get_post($prod_id);
        if ($product && $product->post_type === 'product') {
            wp_set_object_terms($prod_id, $data['tags'], 'product_tag', false);
        } else {
            // Try matching by exact title
            $found = get_page_by_title($data['title'], OBJECT, 'product');
            if ($found) {
                wp_set_object_terms($found->ID, $data['tags'], 'product_tag', false);
            }
        }
    }

    // 2. Seed Blog Post SEO Tags (post_tag)
    $post_map = basate_nab_get_post_seo_tags_map();
    foreach ($post_map as $slug => $data) {
        $args = array(
            'name'        => $slug,
            'post_type'   => 'post',
            'post_status' => 'publish',
            'numberposts' => 1
        );
        $posts = get_posts($args);
        if (!empty($posts)) {
            wp_set_post_tags($posts[0]->ID, $data['tags'], false);
        } else {
            $by_title = get_page_by_title($data['title'], OBJECT, 'post');
            if ($by_title) {
                wp_set_post_tags($by_title->ID, $data['tags'], false);
            }
        }
    }

    // 3. Ensure language and timezone options are strictly synced
    if (get_option('WPLANG') !== 'fa_IR') {
        update_option('WPLANG', 'fa_IR');
    }
    if (get_option('timezone_string') !== 'Asia/Tehran') {
        update_option('timezone_string', 'Asia/Tehran');
    }
    if (get_option('date_format') !== 'j F Y') {
        update_option('date_format', 'j F Y');
    }

    update_option('basate_nab_seo_tags_seeded_v1', '1');
}

add_action('init', function() {
    if (!get_option('basate_nab_seo_tags_seeded_v1')) {
        basate_nab_seed_seo_tags();
    }
});

// REST Endpoint for manual / programmatic tag synchronization
add_action('rest_api_init', function() {
    register_rest_route('basate-nab/v1', '/sync-seo-tags', array(
        'methods'             => array('GET', 'POST'),
        'callback'            => function() {
            basate_nab_seed_seo_tags();
            
            // Calculate totals
            $total_product_tags = wp_count_terms(array('taxonomy' => 'product_tag', 'hide_empty' => false));
            $total_post_tags = wp_count_terms(array('taxonomy' => 'post_tag', 'hide_empty' => false));
            
            return rest_ensure_response(array(
                'success'            => true,
                'message'            => 'All SEO-friendly tags seeded successfully for products and blog posts.',
                'total_product_tags' => (int)$total_product_tags,
                'total_post_tags'    => (int)$total_post_tags,
                'locale'             => get_locale()
            ));
        },
        'permission_callback' => '__return_true'
    ));
});
