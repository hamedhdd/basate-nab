function basate_nab_get_or_create_blog_attachment($filename) {
    $theme_dir = get_template_directory();
    $filepath = $theme_dir . '/assets/images/blog/' . $filename;
    if (!file_exists($filepath)) {
        return 0;
    }

    $title = sanitize_title(preg_replace('/\.[^.]+$/', '', $filename));

    // Check if attachment already exists by title
    $existing = get_page_by_title($title, OBJECT, 'attachment');
    if ($existing) {
        return $existing->ID;
    }

    // Copy to uploads
    $upload_dir = wp_upload_dir();
    $dest_file = $upload_dir['path'] . '/' . $filename;
    if (!copy($filepath, $dest_file)) {
        return 0;
    }

    $wp_filetype = wp_check_filetype($filename, null);
    $attachment = array(
        'post_mime_type' => $wp_filetype['type'],
        'post_title'     => $title,
        'post_content'   => '',
        'post_status'    => 'inherit'
    );

    $attach_id = wp_insert_attachment($attachment, $dest_file);
    if (!is_wp_error($attach_id) && $attach_id) {
        require_once(ABSPATH . 'wp-admin/includes/image.php');
        $attach_data = wp_generate_attachment_metadata($attach_id, $dest_file);
        wp_update_attachment_metadata($attach_id, $attach_data);
        return $attach_id;
    }

    return 0;
}

