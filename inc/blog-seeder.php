// Automatically seed SEO blog posts into WordPress database
function basate_nab_seed_seo_blog_posts() {
    if (get_option('basate_nab_seo_blog_posts_synced_v1') === '1') return;

    $posts = basate_nab_get_initial_seo_posts();

    foreach ($posts as $item) {
        $existing = get_page_by_path($item['slug'], OBJECT, 'post');
        if ($existing) continue;

        // Ensure category exists
        $cat_id = 0;
        $term = term_exists($item['category'], 'category');
        if (!$term) {
            $term = wp_insert_term($item['category'], 'category');
        }
        if (!is_wp_error($term)) {
            $cat_id = is_array($term) ? $term['term_id'] : $term;
        }

        // Insert Post
        $post_id = wp_insert_post(array(
            'post_title'    => $item['title'],
            'post_name'     => $item['slug'],
            'post_content'  => trim($item['content']),
            'post_excerpt'  => $item['excerpt'],
            'post_status'   => 'publish',
            'post_type'     => 'post',
            'post_category' => $cat_id ? array($cat_id) : array()
        ));

        if ($post_id && !empty($item['media_id'])) {
            set_post_thumbnail($post_id, $item['media_id']);
        }
    }

    // Ensure dedicated blog page exists with slug 'blog'
    $blog_page = get_page_by_path('blog');
    if (!$blog_page) {
        $blog_page_id = wp_insert_post(array(
            'post_title'     => 'وبلاگ و دانشنامه دکوراسیون وینتیج',
            'post_name'      => 'blog',
            'post_status'    => 'publish',
            'post_type'      => 'page',
            'page_template'  => 'page-blog.php'
        ));
    } else {
        update_post_meta($blog_page->ID, '_wp_page_template', 'page-blog.php');
    }

    // Delete default placeholder "Hello world!" post if present
    $hello = get_post(1);
    if ($hello && $hello->post_name === 'hello-world') {
        wp_delete_post(1, true);
    }

    update_option('basate_nab_seo_blog_posts_synced_v1', '1');
}
add_action('init', 'basate_nab_seed_seo_blog_posts');
